import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {webcrypto} from 'node:crypto';
import {runInNewContext} from 'node:vm';

const html=readFileSync(new URL('./Madar.html',import.meta.url),'utf8');
assert.equal(html,readFileSync(new URL('./index.html',import.meta.url),'utf8'));
const functions=html.slice(html.indexOf('async function backupDigest('),html.indexOf('async function exportData('));
const context={crypto:webcrypto,TextEncoder,Uint8Array,Array,JSON,Object};
runInNewContext(functions+'\nthis.pack=backupEnvelope;this.verify=backupVerify;',context);
const old={schema:1,settings:{profileName:'اختبار'},tasks:[{id:'one',title:'مهمة خاصة'}],debts:[],exercises:[],books:[]};
const sealed=await context.pack(old);
assert.match(sealed.madarBackupIntegrity.hash,/^[0-9a-f]{64}$/);
assert.equal(old.madarBackupIntegrity,undefined,'Export must not change the saved object');
const roundtrip=await context.verify(JSON.parse(JSON.stringify(sealed)));
assert.equal(roundtrip.verified,true);
assert.equal(JSON.stringify(roundtrip.data),JSON.stringify(old));
const tampered=JSON.parse(JSON.stringify(sealed));tampered.tasks[0].title='مهمة تغيرت';
await assert.rejects(context.verify(tampered),/تغيّر محتوى الملف/);
await assert.rejects(context.verify({...old,madarBackupIntegrity:{version:1,algorithm:'SHA-256',hash:'wrong'}}),/بصمة سلامة/);
assert.equal((await context.verify(old)).verified,false,'Older JSON remains importable');

const importSource=html.match(/^async function readImport\([^\n]+/m)?.[0];
assert.ok(importSource);
const messages=[],modals=[];
const importer={backupVerify:context.verify,validateData:v=>{if(v.schema!==1)throw Error('schema')},openModal:(...args)=>modals.push(args),toast:(...args)=>messages.push(args),num:String,esc:String,btn:()=>'',D:old,defaults:()=>({schema:1,settings:{}}),preserveBeforeReplace:async()=>{},$:()=>({value:'selected'})};
runInNewContext('let pendingImport=null;'+importSource+'\nthis.importFile=readImport;this.getPending=()=>pendingImport;',importer);
const file=data=>({size:JSON.stringify(data).length,name:'backup.json',text:async()=>JSON.stringify(data)});
await importer.importFile(file(tampered));
assert.equal(modals.length,0,'Corrupt backup must not present replacement');
assert.equal(importer.getPending(),null);
assert.match(messages.at(-1)[0],/تغيّر محتوى الملف/);
await importer.importFile(file(old));
assert.equal(modals.length,1,'Legacy backup is accepted');
assert.equal(importer.getPending().tasks[0].title,'مهمة خاصة');
await importer.importFile(file(sealed));
assert.equal(modals.length,2,'Verified backup is accepted');
assert.equal(importer.getPending().madarBackupIntegrity,undefined,'Integrity metadata is not persisted');
await modals[1][2]();
assert.equal(importer.D.tasks[0].title,'مهمة خاصة','Validated import can still be committed');
console.log('Backup integrity, corrupt rejection and legacy import compatibility passed');
