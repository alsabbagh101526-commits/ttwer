import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';

const html=readFileSync(new URL('./Madar.html',import.meta.url),'utf8');
const module=html.match(/<script id="harvestModule">([\s\S]*?)<\/script>/)?.[1];
assert.ok(module,'The monthly feature must ship in the public HTML');
const source=module.slice(module.indexOf('function harvestMonthRange'),module.indexOf('function harvestCompare'));
const empty=()=>({monthDays:[],faithDays:[],journalDays:[],lifeEvents:[],expenses:[],incomes:[],payments:[],moneyMoves:[],sessions:[],readings:[],books:[],tasks:[],habitLogs:[],wins:[],careDays:[]});
const D=empty();
const context={D,round:n=>Math.round((n+Number.EPSILON)*100)/100,today:()=> '2024-03-15',parseDate:s=>new Date(s+'T12:00:00'),localDate:d=>[d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-'),FAITH_PRAYERS:[['fajr','الفجر'],['dhuhr','الظهر'],['asr','العصر'],['maghrib','المغرب'],['isha','العشاء']]};
runInNewContext(source,context);
const report=m=>runInNewContext(`harvestReport('${m}')`,context);
assert.equal(report('2024-02').range.days,29,'leap year');
assert.equal(report('2023-02').range.days,28,'common year');
assert.equal(report('2024-03').range.elapsed,15,'current partial month');
assert.equal(report('2024-04').range.elapsed,0,'future month');
assert.equal(report('2024-02').prayer.unrecorded,145,'empty prayer entries are unknown, not missed');
D.faithDays.push({date:'2024-02-01',checks:{fajrFard:true},prayers:{fajr:{state:'on_time',mode:'mosque'},dhuhr:{state:'missed',mode:'unknown'}},quranPages:3,harvestExtras:{fast:'yes'}});
const prayer=report('2024-02');
assert.equal(prayer.prayer.on_time,1);
assert.equal(prayer.prayer.modes.mosque,1,'prayer mode does not add another prayer to the status total');
assert.equal(prayer.prayer.missed,1);
assert.equal(prayer.prayer.unrecorded,143);
assert.equal(prayer.fastDays,1);
D.incomes.push({id:'i1',date:'2024-02-01',amount:2000});
D.expenses.push({id:'e1',date:'2024-02-01',amount:850,category:'الطعام',essential:true,recurring:false});
D.expenses.push({id:'e2',date:'2024-02-02',amount:100,category:'الترفيه',essential:false,recurring:false});
D.expenses.push({id:'template',date:'2024-02-01',amount:900,recurring:true});
D.payments.push({id:'p1',date:'2024-02-02',amount:300});
D.moneyMoves.push({id:'m1',date:'2024-02-02',amount:150,kind:'saving'},{id:'m2',date:'2024-02-02',amount:50,kind:'transfer'});
const finance=report('2024-02').finance;
assert.equal(finance.expense,950,'debt principal, internal transfer, and forecast are excluded');
assert.equal(finance.net,1050);
assert.equal(finance.paid,300);
assert.equal(finance.saved,150);
assert.equal(finance.categories['الطعام'],850);
assert.equal(finance.nonessential,100);
assert.equal(report('2024-01').finance.expenseRecorded,false,'empty prior month is not a comparable zero');
D.books.push({id:'b1',finishedAt:'2024-02-03',status:'done'});
assert.equal(report('2024-02').finishedBooks.length,1,'only dated completions count');
console.log('harvest accounting and calendar tests passed');
