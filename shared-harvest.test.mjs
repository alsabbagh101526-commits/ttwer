import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';

const html=readFileSync(new URL('./Madar.html',import.meta.url),'utf8');
const module=html.match(/<script id="harvestModule">([\s\S]*?)<\/script>/)?.[1];
assert.ok(module?.includes('function sharedHarvestMonth'));
assert.ok(html.includes("['harvest','حصاد الشهر المختصر']"));
assert.ok(html.includes('F.meta.harvestAreas=areas'));
const definitions=module.slice(module.indexOf('const SHARED_HARVEST_AREAS='),module.indexOf('let sharedHarvestSelected='));
const month={month:'2026-10',range:{elapsed:18},tasks:[{id:'visible',private:false},{id:'secret',private:true}],done:[{id:'visible',private:false},{id:'secret',private:true}],faith:[],incomes:[],expenses:[],payments:[],sessions:[],sleepLogged:0,readings:[],finishedBooks:[],daily:[],events:[],moodDays:0};
const D={settings:{currency:'SAR'}};
const F={meta:{scopes:{harvest:true},harvestAreas:{tasks:true}},familyId:'room'};
const context={D,F,buildSharedSnapshot:()=>({scopes:{tasks:true},tasks:[]}),today:()=> '2026-10-18',addMonths:(date,n)=>{const d=new Date(date+'T12:00:00Z');d.setUTCMonth(d.getUTCMonth()+n);return d.toISOString().slice(0,10)},harvestReport:m=>({...month,month:m}),SHARED_HARVEST_AREAS:null};
delete context.SHARED_HARVEST_AREAS;
runInNewContext(definitions+'\nthis.getMonth=sharedHarvestMonth;this.snapshot=buildSharedSnapshot;',context);
const summary=context.getMonth(month,{tasks:true,finance:true,relationships:true});
assert.equal(summary.sections.tasks.done,1,'Private completed task does not enter shared totals');
assert.equal(summary.sections.tasks.planned,1);
assert.equal('finance' in summary.sections,false,'No financial disclosure without records');
assert.equal('relationships' in summary.sections,false);
const snapshot=context.snapshot();
assert.equal(snapshot.scopes.harvest,true);
assert.equal(snapshot.harvestAreas.tasks,true);
assert.equal(snapshot.harvestAreas.finance,false);
assert.equal(snapshot.harvest.length,12);
assert.equal(snapshot.harvestCurrency,'SAR');
F.meta.scopes={harvest:false};
const revoked=context.snapshot();
assert.equal('harvest' in revoked,false,'Turning sharing off removes monthly data');
console.log('Shared harvest client privacy tests passed');
